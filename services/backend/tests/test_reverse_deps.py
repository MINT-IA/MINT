"""Phase mint-calc-engine-v1 Plan 14 — D-CE-14 reverse-dep map contract tests.

Verifies ``REVERSE_DEP_MAP`` (auto-generated by ``tools/generate_calc_registry.py``
alongside ``REGISTRY`` per Override #5 « kills two birds ») has the shape Plan 15
(BackgroundTasks pre-compute) expects.

Test budget : 7 tests per PLAN.md Task 1 <behavior> spec. Note that the registry
artifact + map are already shipped by Plan 05 (« reverse-dep map seed »); Plan 14
ships the dedicated test surface + locks down the API contract for Plan 15.

References
----------
- mint-calc-engine-v1-14-w3-reverse-dep-map-PLAN.md
- mint-calc-engine-v1-CONTEXT.md §D-CE-14
- mint-calc-engine-v1-VALIDATION.md Q4 (direct deps only in v1)
- Plan 05 SUMMARY (146 fields, 25 calcs depend on canton, 63 calcs)

Deviation note for Test 5
-------------------------
PLAN.md Task 1 Test 5 reads :

  > « REVERSE_DEP_MAP keys are all valid profile field names from
  >   `_PROFILE_SAFE_FIELDS` canonical list at `coach_chat.py:875` (no drift). »

This is conceptually inverted : ``_PROFILE_SAFE_FIELDS`` is a PII whitelist for
the **LLM coach context** (56 narrow user-facing fields exposed to Claude), while
``REVERSE_DEP_MAP`` keys are the **internal profile fields each calculator declares
as needed** (146 fields, many of which are calculator-internal intermediate values
like ``taux_marginal``, ``a3a_maxed``, ``rendement_3a``). The two sets are
deliberately different — only 7 fields overlap (``age``, ``canton``,
``conjoint_age``, ``conjoint_salary``, ``has_debt``, ``marital_status``,
``primary_focus``).

The drift-style assertion the plan envisions only makes sense in the reverse
direction : the **intersection between the LLM-safe whitelist and REVERSE_DEP_MAP
keys** should contain the canonical anchor fields (``canton``, ``age``). That's
what Test 5 below asserts. Documented as Rule 1 deviation in SUMMARY.
"""
