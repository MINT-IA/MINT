# ---------------------------------------------------------------------------
# Test 5 — anchor fields from _PROFILE_SAFE_FIELDS are present in the map
# ---------------------------------------------------------------------------


def test_reverse_dep_map_includes_pii_safe_anchor_fields():
    """The canonical anchor fields shared between PII-safe LLM whitelist and
    internal calculator deps (``canton``, ``age``) must appear in the map.

    Reframed from PLAN.md Test 5 — see module docstring for rationale.
    The original Test 5 assertion (« REVERSE_DEP_MAP keys ⊆ _PROFILE_SAFE_FIELDS »)
    is conceptually inverted because the two sets describe different concerns :
    PII safety (56 LLM-facing fields) vs internal calculator deps (146 fields
    including calculator-internal intermediates like ``taux_marginal``).
    The well-formed assertion is that the *intersection* contains the anchors.
    """
    from app.calculators import REVERSE_DEP_MAP
    from app.api.v1.endpoints.coach_chat import _PROFILE_SAFE_FIELDS

    rev_keys = set(REVERSE_DEP_MAP.keys())
    intersection = rev_keys & _PROFILE_SAFE_FIELDS

    # Canonical anchors that exist in BOTH the PII-safe whitelist and the
    # internal calculator dep map. ``canton`` + ``age`` are the must-haves.
    must_have_anchors = {"canton", "age"}
    missing = must_have_anchors - intersection
    assert not missing, (
        f"Canonical anchor fields missing from REVERSE_DEP_MAP ∩ "
        f"_PROFILE_SAFE_FIELDS : {sorted(missing)}. "
        "These are the bridge fields Plan 15 pre-compute relies on to drive "
        "downstream cache invalidation when the LLM updates user profile."
    )

    # Plan-level smoke check : the bridge intersection is non-trivial (≥5).
    assert len(intersection) >= 5, (
        f"REVERSE_DEP_MAP ∩ _PROFILE_SAFE_FIELDS has only "
        f"{len(intersection)} fields ({sorted(intersection)}). "
        "Expected at least 5 bridge fields for Plan 15 pre-compute coverage."
    )


# ---------------------------------------------------------------------------
# Test 6 — regeneration is idempotent
# ---------------------------------------------------------------------------


def test_reverse_dep_map_regeneration_is_idempotent():
    """``python3 tools/generate_calc_registry.py --check`` exits 0 immediately
    after a fresh write.

    Locks the « D-CE-14 kills two birds » contract : if a future commit modifies
    ``_registry.py`` by hand (forbidden), the next ``--check`` run fails CI.
    """
    result = subprocess.run(
        [sys.executable, str(GENERATOR_PATH), "--check"],
        cwd=PROJECT_ROOT,
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert result.returncode == 0, (
        f"generate_calc_registry.py --check failed with exit "
        f"{result.returncode}.\nstdout : {result.stdout}\nstderr : {result.stderr}"
    )


# ---------------------------------------------------------------------------
# Test 7 — every value in REVERSE_DEP_MAP is a set of names ALL in REGISTRY
# ---------------------------------------------------------------------------


def test_reverse_dep_map_values_are_all_valid_calc_names():
    """No orphan : every calc name in any REVERSE_DEP_MAP value set must
    exist as a key in REGISTRY.

    Catches regressions where the generator emits a stale calc name (e.g.
    if a service file is renamed but the dep map is not regenerated).
    """
    from app.calculators import REGISTRY, REVERSE_DEP_MAP

    registry_keys = set(REGISTRY.keys())
    orphans: dict[str, set[str]] = {}
    for field, calcs in REVERSE_DEP_MAP.items():
        assert isinstance(calcs, set), (
            f"REVERSE_DEP_MAP[{field!r}] is {type(calcs).__name__}, expected set"
        )
        bad = calcs - registry_keys
        if bad:
            orphans[field] = bad

    assert not orphans, (
        f"REVERSE_DEP_MAP has {sum(len(v) for v in orphans.values())} orphan "
        f"calc names across {len(orphans)} fields. Sample : "
        f"{dict(list(orphans.items())[:3])}"
    )
